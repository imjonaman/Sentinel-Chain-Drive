"""MuleChain fraud intelligence alerts and pattern indicators."""

import enum
import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    JSON,
    DateTime,
    Enum,
    ForeignKey,
    Integer,
    String,
    UniqueConstraint,
    Uuid,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from sentinel_chain_drive.db.base import Base, TimestampMixin, UUIDPrimaryKeyMixin


class AlertSeverity(enum.StrEnum):
    """Risk severity classification for fraud alerts."""

    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class AlertStatus(enum.StrEnum):
    """Investigation lifecycle status for fraud alerts."""

    NEW = "NEW"
    INVESTIGATING = "INVESTIGATING"
    RESOLVED = "RESOLVED"
    FALSE_POSITIVE = "FALSE_POSITIVE"


class DetectorType(enum.StrEnum):
    """Topological fraud pattern detector classifications."""

    FAN_IN = "FAN_IN"
    FAN_OUT = "FAN_OUT"
    RAPID_PASSTHROUGH = "RAPID_PASSTHROUGH"
    CIRCULAR_LAYERING = "CIRCULAR_LAYERING"


class FraudAlert(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """MuleChain fraud intelligence alert generated by graph topology analysis."""

    __tablename__ = "fraud_alerts"

    alert_code: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        index=True,
        comment="Machine-readable alert code, e.g., MULE_FAN_IN, MULE_RAPID_PASSTHROUGH",
    )
    detector_type: Mapped[DetectorType] = mapped_column(
        Enum(DetectorType, name="detector_type_enum", native_enum=False),
        nullable=False,
        index=True,
        comment="Underlying graph topology detector type",
    )
    severity: Mapped[AlertSeverity] = mapped_column(
        Enum(AlertSeverity, name="alert_severity_enum", native_enum=False),
        nullable=False,
        default=AlertSeverity.MEDIUM,
        index=True,
        comment="Risk severity level: LOW, MEDIUM, HIGH, or CRITICAL",
    )
    status: Mapped[AlertStatus] = mapped_column(
        Enum(AlertStatus, name="alert_status_enum", native_enum=False),
        nullable=False,
        default=AlertStatus.NEW,
        index=True,
        comment="Lifecycle investigation status",
    )
    risk_score: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        index=True,
        comment="Explainable risk prioritization score from 0 to 100",
    )
    primary_institution_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("institutions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        comment="Scoped financial institution owner of the alert",
    )
    primary_account_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("accounts.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
        comment="Focal account associated with the suspicious pattern",
    )
    currency: Mapped[str] = mapped_column(
        String(3),
        nullable=False,
        comment="ISO 4217 currency code of the fund flows analyzed",
    )
    analysis_window_start: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        comment="Start timestamp of the historical analysis window",
    )
    analysis_window_end: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        comment="End timestamp of the historical analysis window",
    )
    detection_rule_version: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        default="v1.0",
        comment="Version of the pattern detector rule",
    )
    scoring_model_version: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        default="v1.0",
        comment="Version of the risk scoring formula",
    )
    evidence_data: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
        default=dict,
        comment="Structured evidence trace: accounts, transaction IDs, and thresholds",
    )
    dedup_fingerprint: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        index=True,
        comment="Deterministic SHA-256 fingerprint for alert deduplication and idempotency",
    )

    # Relationships
    institution = relationship("Institution", lazy="selectin")
    account = relationship("Account", lazy="selectin")

    __table_args__ = (
        UniqueConstraint(
            "primary_institution_id",
            "dedup_fingerprint",
            name="uq_fraud_alerts_institution_fingerprint",
        ),
    )

    def __init__(
        self,
        *,
        alert_code: str,
        detector_type: DetectorType,
        severity: AlertSeverity,
        risk_score: int,
        primary_institution_id: uuid.UUID,
        currency: str,
        analysis_window_start: datetime,
        analysis_window_end: datetime,
        evidence_data: dict[str, Any],
        dedup_fingerprint: str,
        primary_account_id: uuid.UUID | None = None,
        status: AlertStatus = AlertStatus.NEW,
        detection_rule_version: str = "v1.0",
        scoring_model_version: str = "v1.0",
        **kwargs: Any,
    ) -> None:
        super().__init__(**kwargs)
        self.alert_code = alert_code
        self.detector_type = detector_type
        self.severity = severity
        self.risk_score = risk_score
        self.primary_institution_id = primary_institution_id
        self.primary_account_id = primary_account_id
        self.currency = currency
        self.analysis_window_start = analysis_window_start
        self.analysis_window_end = analysis_window_end
        self.evidence_data = evidence_data
        self.dedup_fingerprint = dedup_fingerprint
        self.status = status
        self.detection_rule_version = detection_rule_version
        self.scoring_model_version = scoring_model_version
